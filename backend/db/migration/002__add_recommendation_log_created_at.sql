CREATE TABLE IF NOT EXISTS notification_place_recommendation_log (
    recommendation_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    report_id BIGINT NOT NULL,
    place_name VARCHAR(20) NOT NULL,
    address TEXT NOT NULL,
    coordinate geometry(Point, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_notification_place_recommendation_log
    PRIMARY KEY (recommendation_log_id),

    CONSTRAINT fk_notification_place_recommendation_log_user
    FOREIGN KEY (user_id)
    REFERENCES users (user_id),

    CONSTRAINT fk_notification_place_recommendation_log_report
    FOREIGN KEY (report_id)
    REFERENCES report (report_id)
    );

