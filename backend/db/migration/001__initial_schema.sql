CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(10) NOT NULL,
    provider_sub VARCHAR(255) NOT NULL,
    nickname VARCHAR(20),
    role VARCHAR(10) NOT NULL,

    CONSTRAINT uk_users_provider_provider_sub
        UNIQUE (provider, provider_sub),
    CONSTRAINT ck_users_provider
        CHECK (provider IN ('GOOGLE')),
    CONSTRAINT ck_users_role
        CHECK (role IN ('GUEST', 'USER'))
);

CREATE TABLE category (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(20) NOT NULL,

    CONSTRAINT fk_category_user
        FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE my_place (
    my_place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    place_name VARCHAR(20) NOT NULL,
    address VARCHAR(50) NOT NULL,
    coordinate geometry(Point, 4326) NOT NULL,

    CONSTRAINT fk_my_place_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT uk_my_place_user_place_name
        UNIQUE (user_id, place_name)
);

CREATE TABLE report (
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    type VARCHAR(10) NOT NULL,
    total_cost BIGINT NOT NULL,
    highest_spending_place TEXT NOT NULL,
    most_frequent_place TEXT NOT NULL,
    ai_answer TEXT NOT NULL,

    CONSTRAINT fk_report_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_report_type
        CHECK (type IN ('WEEKLY', 'MONTHLY'))
);

CREATE TABLE notification_place (
    notification_place_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    notification_place_name VARCHAR(20) NOT NULL,
    address VARCHAR(50) NOT NULL,
    coordinate geometry(Point, 4326) NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    reason VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_notification_place_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT uk_notification_place_name_user
        UNIQUE (user_id, notification_place_name)
);

CREATE TABLE transaction_history (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    datetime TIMESTAMPTZ NOT NULL,
    amount BIGINT NOT NULL,
    type VARCHAR(10) NOT NULL,
    transaction_name VARCHAR(10) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    branch VARCHAR(30),
    memo VARCHAR(30),
    address TEXT,
    b_code VARCHAR(10),
    region_1depth_name TEXT,
    region_2depth_name TEXT,
    region_3depth_name TEXT,
    coordinate geometry(Point, 4326),

    CONSTRAINT fk_transaction_history_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_transaction_history_category
        FOREIGN KEY (category_id) REFERENCES category (category_id),
    CONSTRAINT ck_transaction_history_type
        CHECK (type IN ('INCOME', 'EXPENSE'))
);

CREATE TABLE user_push_tokens (
    push_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    device_type VARCHAR(10) NOT NULL,
    push_token TEXT NOT NULL,

    CONSTRAINT fk_user_push_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT ck_user_push_tokens_device_type
        CHECK (device_type IN ('ANDROID', 'IOS', 'WEB'))
);

CREATE TABLE refresh_tokens (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT uk_refresh_tokens_user_id
        UNIQUE (user_id)
);

CREATE TABLE notification_place_recommendation_log (
    recommendation_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    report_id BIGINT NOT NULL,
    place_name VARCHAR(20) NOT NULL,
    address TEXT NOT NULL,
    coordinate geometry(Point, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT fk_recommendation_log_user
        FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_recommendation_log_report
        FOREIGN KEY (report_id) REFERENCES report (report_id)
);
